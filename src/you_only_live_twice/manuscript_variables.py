"""Manuscript ``{{TOKEN}}`` hydration for the VOLCANO manuscript.

Loads ``manuscript/config.yaml`` (paper identity) and computes the live metrics
the manuscript prose injects, entirely from the deterministic mission scenario
via the single analysis source :func:`you_only_live_twice.scenario.solve_mission`
(the same results the mission adapter reports). No metric is hand-authored in
prose — every numeric claim flows through this module.

The token map is generated by :func:`generate_variables`; a live cross-reference
test (``tests/test_manuscript_variables.py``) scans ``manuscript/[0-9]*.md`` and
fails if any ``{{TOKEN}}`` used in prose is not produced here.
"""

from __future__ import annotations

import math
import platform
import sys
from pathlib import Path
from typing import Any

import yaml
from bond_api.protocol import protocol_surface

from you_only_live_twice.figures import FIGURE_FILENAMES
from you_only_live_twice.scenario import (
    CODENAME,
    PACKAGE_VERSION,
    SEED,
    build_scenario,
    scenario_descriptor,
    solve_mission,
)

__all__ = ["generate_variables", "load_mission_config"]

#: Path used by scripts when run from the package root.
_DEFAULT_CONFIG = (
    Path(__file__).resolve().parent.parent.parent / "manuscript" / "config.yaml"
)


def load_mission_config(config_path: Path | None = None) -> dict[str, Any]:
    """Load the mission's manuscript configuration as a dict."""
    path = Path(config_path) if config_path is not None else _DEFAULT_CONFIG
    if not path.is_file():
        raise FileNotFoundError(f"manuscript config not found: {path}")
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise TypeError(f"manuscript config must be a mapping: {path}")
    return data


def _mission_metrics() -> dict[str, Any]:
    """Live metrics from the single analysis source (used by the token map)."""
    scenario = build_scenario()
    analysis = solve_mission(scenario)
    rendezvous = analysis["rendezvous"]
    capture = analysis["capture"]
    lair = analysis["concealed_lair"]
    discovery = analysis["hidden_base_discovery"]
    infiltration = analysis["infiltration"]
    emitter = analysis["emitter_localization"]
    pattern = analysis["pattern_of_life"]

    return {
        "seed": SEED,
        "input_hash": scenario["input_hash"],
        "rendezvous": rendezvous,
        "capture": capture,
        "lair": lair,
        "discovery": discovery,
        "infiltration": infiltration,
        "emitter": emitter,
        "pattern": pattern,
    }


def generate_variables(
    require_analysis_outputs: bool = True,
    config_path: Path | None = None,
    now: str | None = None,
) -> dict[str, str]:
    """Compute the full ``{{TOKEN}}`` mapping for the VOLCANO manuscript.

    Args:
        require_analysis_outputs: accepted for parity with the suite convention;
            metrics here are always computed deterministically.
        config_path: optional override path to ``manuscript/config.yaml``.
        now: optional fixed generation timestamp (for deterministic tests).

    Returns a ``{token: str_value}`` mapping.
    """
    del require_analysis_outputs
    config = load_mission_config(config_path)
    paper = config.get("paper", {}) if isinstance(config.get("paper", {}), dict) else {}

    surface = protocol_surface()
    desc = scenario_descriptor()
    m = _mission_metrics()
    rv, cap = m["rendezvous"], m["capture"]
    lair, disc = m["lair"], m["discovery"]
    infil, emit = m["infiltration"], m["emitter"]
    pat = m["pattern"]

    if now is None:
        now = "2026-08-04"  # fixed manuscript generation date (local-only)

    peak_windows_str = "; ".join(f"{a:02d}-{b:02d}h" for a, b in pat["peak_windows"])
    period = pat["dominant_period_hours"]
    period_hours = (
        round(period, 1)
        if not (isinstance(period, float) and math.isnan(period))
        else None
    )

    variables: dict[str, str] = {
        # Identity
        "BOND_IDENTITY": "YOU ONLY LIVE TWICE",
        "BOND_CODENAME": CODENAME,
        "BOND_VERSION": PACKAGE_VERSION,
        "BOND_FILM_YEAR": "1967",
        "BOND_TITLE": str(paper.get("title", "You Only Live Twice: VOLCANO")),
        "BOND_SUBTITLE": str(paper.get("subtitle", "Special-Agent Mission Software")),
        "PYTHON_VERSION": platform.python_version(),
        "GENERATION_TIMESTAMP": now,
        "BOND_NUM_DATACLASSES": str(len(surface["dataclasses"])),
        "BOND_NUM_PROVIDER_METHODS": str(len(surface["provider_methods"])),
        # Scenario
        "SCENARIO_SEED": str(SEED),
        "MISSION_INPUT_HASH": m["input_hash"][:16],
        "NUM_FIGURES": str(len(FIGURE_FILENAMES)),
        # Experimental setup — read straight off the provenance descriptor, so
        # a reported parameter cannot drift from the parameter simulated.
        "SETUP_CHASER_ALT_KM": _fmt(desc["orbits"]["chaser"]["altitude_km"]),
        "SETUP_CHASER_INC_DEG": _fmt(desc["orbits"]["chaser"]["inclination_deg"]),
        "SETUP_CHASER_RAAN_DEG": _fmt(desc["orbits"]["chaser"]["raan_deg"]),
        "SETUP_CHASER_PHASE_RAD": _fmt(desc["orbits"]["chaser"]["phase_rad"]),
        "SETUP_TARGET_ALT_KM": _fmt(desc["orbits"]["target"]["altitude_km"]),
        "SETUP_TARGET_INC_DEG": _fmt(desc["orbits"]["target"]["inclination_deg"]),
        "SETUP_TARGET_RAAN_DEG": _fmt(desc["orbits"]["target"]["raan_deg"]),
        "SETUP_TARGET_PHASE_RAD": _fmt(desc["orbits"]["target"]["phase_rad"]),
        "SETUP_RDV_HORIZON_S": _fmt(desc["rendezvous"]["horizon_s"]),
        "SETUP_RDV_STEP_S": _fmt(desc["rendezvous"]["dt_s"]),
        "SETUP_RDV_MAX_RANGE_KM": _fmt(desc["rendezvous"]["max_range_km"]),
        "SETUP_RDV_MIN_ELEV_DEG": _fmt(desc["rendezvous"]["min_elevation_deg"]),
        "SETUP_CAPTURE_MAX_RANGE_KM": _fmt(desc["capture"]["max_range_km"]),
        "SETUP_CAPTURE_MAX_SPEED_M_S": _fmt(desc["capture"]["max_speed_m_s"]),
        "SETUP_CAPTURE_STEP_S": _fmt(desc["capture"]["dt_s"]),
        "SETUP_GRID_CELLS": _fmt(desc["volcano"]["size"]),
        "SETUP_CONE_RADIUS_CELLS": _fmt(desc["volcano"]["cone_radius_cells"]),
        "SETUP_CONE_HEIGHT_M": _fmt(desc["volcano"]["cone_height_m"]),
        "SETUP_LAIR_HEAT_K": _fmt(desc["volcano"]["lair_heat_kelvin"]),
        "SETUP_ACTIVITY_RATE_PER_H": _fmt(desc["activity"]["base_rate_per_hour"]),
        "SETUP_ACTIVITY_HOURS": _fmt(desc["activity"]["hours"]),
        "SETUP_DISCOVERY_MU_HOT": _fmt(desc["discovery"]["mu_hot"]),
        "SETUP_DISCOVERY_BETA": _fmt(desc["discovery"]["beta"]),
        "SETUP_DISCOVERY_RF_POWER": _fmt(desc["discovery"]["rf_power"]),
        "SETUP_INFIL_SLOPE_WEIGHT": _fmt(desc["infiltration"]["slope_weight"]),
        "SETUP_INFIL_THERMAL_WEIGHT": _fmt(desc["infiltration"]["thermal_weight"]),
        "SETUP_INFIL_GUARD_WEIGHT": _fmt(desc["infiltration"]["guard_weight"]),
        "SETUP_EMITTER_RING_RADIUS_M": _fmt(desc["emitter"]["ring_radius_m"]),
        "SETUP_EMITTER_SENSORS": _fmt(desc["emitter"]["sensor_count"]),
        "SETUP_EMITTER_TIME_NOISE_NS": _fmt(
            round(desc["emitter"]["time_noise_s"] * 1e9, 3)
        ),
        # Rendezvous
        "RENDEZVOUS_NUM_WINDOWS": str(rv["num_windows"]),
        "RENDEZVOUS_FIRST_START_S": _fmt(rv["first_window_start_s"]),
        "RENDEZVOUS_FIRST_DURATION_S": _fmt(rv["first_window_duration_s"]),
        "RENDEZVOUS_FIRST_ELEV_DEG": _fmt(rv["first_window_peak_elevation_deg"]),
        "RENDEZVOUS_DELTA_V_M_S": _fmt(rv["delta_v_total_m_s"]),
        "RENDEZVOUS_TRANSFER_TIME_S": _fmt(rv["transfer_time_s"]),
        # Orbital capture
        "CAPTURE_NUM_WINDOWS": str(cap["num_windows"]),
        "CAPTURE_FIRST_START_S": _fmt(cap["first_window_start_s"]),
        "CAPTURE_FIRST_DURATION_S": _fmt(cap["first_window_duration_s"]),
        "CAPTURE_GRAPPLE_DV_M_S": _fmt(cap["grapple_delta_v_m_s"]),
        "CAPTURE_PHASING_LEAD_DEG": _fmt(cap["phasing_lead_deg"]),
        "CAPTURE_PHASING_WAIT_S": _fmt(cap["phasing_wait_s"]),
        # Concealed lair
        "LAIR_NUM_CANDIDATES": str(lair["num_candidates"]),
        "LAIR_TOP_FUSED_SCORE": _fmt(lair["top_fused_score"]),
        "LAIR_TOP_THERMAL_SCORE": _fmt(lair["top_thermal_score"]),
        "LAIR_TOP_TERRAIN_SCORE": _fmt(lair["top_terrain_score"]),
        "LAIR_TOP_AREA_CELLS": str(lair["top_area_cells"]),
        "LAIR_FOOTPRINT_CELLS": str(lair["footprint_cells"]),
        "LAIR_DETECTOR_OFFSET_M": _fmt(lair["detector_offset_m"]),
        "LAIR_DETECTOR_OFFSET_CELLS": _fmt(lair["detector_offset_cells"]),
        "LAIR_DETECTED_IN_FOOTPRINT": "yes" if lair["detected_in_footprint"] else "no",
        # Hidden-base discovery. Two ground-truth questions are reported
        # separately and must not be conflated: did the search find the
        # *facility* (footprint), and did it land on the injected *centre cell*
        # (centroid)? The second is far stricter and this scene fails it.
        "DISCOVERY_FOOTPRINT_RANK": str(disc["footprint_rank"]),
        "DISCOVERY_FOOTPRINT_POSTERIOR": _fmt(disc["footprint_posterior"]),
        "DISCOVERY_FOOTPRINT_CELLS": str(disc["footprint_cells"]),
        "DISCOVERY_CENTROID_RANK": str(disc["centroid_rank"]),
        "DISCOVERY_CENTROID_POSTERIOR": _fmt(disc["centroid_posterior"]),
        "DISCOVERY_PEAK_OFFSET_M": _fmt(disc["peak_offset_m"]),
        "DISCOVERY_SINGLE_CUE_RANKS": ", ".join(
            f"{name} {rank}"
            for name, rank in sorted(disc["single_cue_footprint_ranks"].items())
        ),
        "DISCOVERY_EXPECTED_EFFORT_CELLS": _fmt(disc["expected_effort_cells"]),
        "DISCOVERY_P_FIRST_10": _fmt(disc["prob_found_first_10"]),
        "DISCOVERY_CANDIDATE_CELLS": str(disc["num_candidate_cells"]),
        # Infiltration
        "INFILTRATION_ROUTE_COST": _fmt(infil["route_cost"]),
        "INFILTRATION_PATH_LENGTH": str(infil["path_length"]),
        "INFILTRATION_EXPANDED": str(infil["expanded"]),
        "INFILTRATION_EXPOSURE": _fmt(infil["thermal_exposure"]),
        "INFILTRATION_BASELINE_COST": _fmt(infil["baseline_cost"]),
        "INFILTRATION_REDUCTION": _fmt(infil["cost_reduction"]),
        "INFILTRATION_REDUCTION_PCT": _fmt(round(infil["cost_reduction"] * 100.0, 2)),
        # Emitter localization
        "EMITTER_ERROR_M": _fmt(emit["error_m"]),
        "EMITTER_ITERATIONS": str(emit["iterations"]),
        "EMITTER_SENSORS": str(emit["num_sensors"]),
        "EMITTER_TIME_NOISE_NS": _fmt(round(emit["time_noise_s"] * 1e9, 3)),
        "EMITTER_IMAGERY_OFFSET_M": _fmt(emit["imagery_site_offset_m"]),
        "EMITTER_TRUTH_IMAGERY_OFFSET_M": _fmt(emit["truth_to_imagery_offset_m"]),
        # Pattern of life
        "PATTERN_NUM_EVENTS": str(pat["num_events"]),
        "PATTERN_DOMINANT_PERIOD_H": _fmt(period_hours),
        "PATTERN_TEMPO": pat["tempo"],
        "PATTERN_DUTY_CYCLE": _fmt(round(pat["duty_cycle"], 3)),
        "PATTERN_NUM_PEAK_WINDOWS": str(len(pat["peak_windows"])),
        "PATTERN_PEAK_WINDOWS": peak_windows_str,
        "SYSTEM": sys.platform,
    }
    return variables


def _fmt(value: Any) -> str:
    """Format a numeric token value; None becomes the literal 'N/A'."""
    if value is None:
        return "N/A"
    return str(value)
