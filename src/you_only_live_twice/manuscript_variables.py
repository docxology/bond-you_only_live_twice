"""Manuscript ``{{TOKEN}}`` hydration for the VOLCANO manuscript.

Loads ``manuscript/config.yaml`` (paper identity) and computes the live metrics
the manuscript prose injects, entirely from the deterministic mission scenario.
No metric is hand-authored in prose — every numeric claim flows through this
module so re-running the analysis re-hydrates the manuscript consistently.

The token map is generated by :func:`generate_variables`; a live cross-reference
test (``tests/test_manuscript_variables.py``) scans ``manuscript/[0-9]*.md`` and
fails if any ``{{TOKEN}}`` used in prose is not produced here.
"""

from __future__ import annotations

import math
import platform
import sys
from pathlib import Path
from typing import Any

import yaml
from bond_api.protocol import protocol_surface

from you_only_live_twice.pattern_of_life import (
    daily_activity_profile,
    dominant_period_hours,
    duty_cycle,
    operational_tempo,
    peak_activity_windows,
)
from you_only_live_twice.rendezvous_windows import (
    find_rendezvous_windows,
    hohmann_transfer,
)
from you_only_live_twice.scenario import (
    CODENAME,
    PACKAGE_VERSION,
    SEED,
    build_scenario,
    scenario_input_hash,
)
from you_only_live_twice.terrain_anomaly import detect_concealed_lair

__all__ = ["generate_variables", "load_mission_config"]

#: Path used by scripts when run from the package root.
_DEFAULT_CONFIG = (
    Path(__file__).resolve().parent.parent.parent / "manuscript" / "config.yaml"
)


def load_mission_config(config_path: Path | None = None) -> dict[str, Any]:
    """Load the mission's manuscript configuration as a dict."""
    path = Path(config_path) if config_path is not None else _DEFAULT_CONFIG
    if not path.is_file():
        raise FileNotFoundError(f"manuscript config not found: {path}")
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise TypeError(f"manuscript config must be a mapping: {path}")
    return data


def _mission_metrics() -> dict[str, Any]:
    """Live metrics from the deterministic scenario (used by the token map)."""
    scenario = build_scenario()
    orbits = scenario["orbits"]
    chaser = orbits["chaser"]
    target = orbits["target"]

    windows = find_rendezvous_windows(chaser, target, t_start=0.0, t_end=86400.0)
    first = windows[0] if windows else None
    transfer = hohmann_transfer(chaser.radius, target.radius)

    regions, _meta = detect_concealed_lair(
        scenario["volcano"]["thermal"], scenario["volcano"]["elevation"]
    )
    top = regions[0] if regions else None

    activity = scenario["activity"]
    profile = daily_activity_profile(activity)
    period = dominant_period_hours(profile)
    tempo = operational_tempo(activity)
    duty = duty_cycle(activity)
    peak = peak_activity_windows(profile)

    return {
        "seed": SEED,
        "input_hash": scenario_input_hash(),
        "num_windows": len(windows),
        "first_window_start_s": round(first.start_s, 1) if first else None,
        "first_window_duration_s": round(first.duration_s, 1) if first else None,
        "first_window_elev_deg": round(first.peak_elevation_deg, 2) if first else None,
        "delta_v_total_m_s": round(transfer["delta_v_total"], 1),
        "transfer_time_s": round(transfer["transfer_time_s"], 1),
        "lair_candidates": len(regions),
        "lair_fused": round(top.fused_score, 3) if top else None,
        "lair_thermal": round(top.thermal_score, 3) if top else None,
        "lair_terrain": round(top.terrain_score, 3) if top else None,
        "lair_area_cells": top.area_cells if top else 0,
        "num_events": len(activity),
        "period_hours": round(period, 1) if not math.isnan(period) else None,
        "tempo": tempo,
        "duty_cycle": round(duty, 3),
        "peak_windows": peak,
        "num_peak_windows": len(peak),
    }


def generate_variables(
    require_analysis_outputs: bool = True,
    config_path: Path | None = None,
    now: str | None = None,
) -> dict[str, str]:
    """Compute the full ``{{TOKEN}}`` mapping for the VOLCANO manuscript.

    Args:
        require_analysis_outputs: when True, unresolved analysis-derived tokens
            raise rather than degrade to placeholders.
        config_path: optional override path to ``manuscript/config.yaml``.
        now: optional fixed generation timestamp (for deterministic tests).

    Returns a ``{token: str_value}`` mapping.
    """
    del require_analysis_outputs  # metrics are always computed deterministically
    config = load_mission_config(config_path)
    paper = config.get("paper", {}) if isinstance(config.get("paper", {}), dict) else {}

    surface = protocol_surface()
    metrics = _mission_metrics()

    if now is None:
        now = (
            "2026-08-04"  # fixed manuscript generation date (local-only, no wall-clock)
        )

    peak_windows_str = "; ".join(
        f"{a:02d}-{b:02d}h" for a, b in metrics["peak_windows"]
    )

    variables: dict[str, str] = {
        # Identity
        "BOND_IDENTITY": "YOU ONLY LIVE TWICE",
        "BOND_CODENAME": CODENAME,
        "BOND_VERSION": PACKAGE_VERSION,
        "BOND_FILM_YEAR": "1967",
        "BOND_TITLE": str(paper.get("title", "You Only Live Twice: VOLCANO")),
        "BOND_SUBTITLE": str(paper.get("subtitle", "Special-Agent Mission Software")),
        # Suite cross-reference
        "PYTHON_VERSION": platform.python_version(),
        "GENERATION_TIMESTAMP": now,
        "BOND_NUM_DATACLASSES": str(len(surface["dataclasses"])),
        "BOND_NUM_PROVIDER_METHODS": str(len(surface["provider_methods"])),
        # Scenario
        "SCENARIO_SEED": str(metrics["seed"]),
        "MISSION_INPUT_HASH": metrics["input_hash"][:16],
        # Rendezvous
        "RENDEZVOUS_NUM_WINDOWS": str(metrics["num_windows"]),
        "RENDEZVOUS_FIRST_START_S": _fmt(metrics["first_window_start_s"]),
        "RENDEZVOUS_FIRST_DURATION_S": _fmt(metrics["first_window_duration_s"]),
        "RENDEZVOUS_FIRST_ELEV_DEG": _fmt(metrics["first_window_elev_deg"]),
        "RENDEZVOUS_DELTA_V_M_S": _fmt(metrics["delta_v_total_m_s"]),
        "RENDEZVOUS_TRANSFER_TIME_S": _fmt(metrics["transfer_time_s"]),
        # Concealed lair
        "LAIR_NUM_CANDIDATES": str(metrics["lair_candidates"]),
        "LAIR_TOP_FUSED_SCORE": _fmt(metrics["lair_fused"]),
        "LAIR_TOP_THERMAL_SCORE": _fmt(metrics["lair_thermal"]),
        "LAIR_TOP_TERRAIN_SCORE": _fmt(metrics["lair_terrain"]),
        "LAIR_TOP_AREA_CELLS": str(metrics["lair_area_cells"]),
        # Pattern of life
        "PATTERN_NUM_EVENTS": str(metrics["num_events"]),
        "PATTERN_DOMINANT_PERIOD_H": _fmt(metrics["period_hours"]),
        "PATTERN_TEMPO": metrics["tempo"],
        "PATTERN_DUTY_CYCLE": _fmt(metrics["duty_cycle"]),
        "PATTERN_NUM_PEAK_WINDOWS": str(metrics["num_peak_windows"]),
        "PATTERN_PEAK_WINDOWS": peak_windows_str,
        "SYSTEM": sys.platform,
    }
    return {k: v for k, v in variables.items()}


def _fmt(value: Any) -> str:
    """Format a numeric token value; None becomes the literal 'N/A'."""
    if value is None:
        return "N/A"
    return str(value)
